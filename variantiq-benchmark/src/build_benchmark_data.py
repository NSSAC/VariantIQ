#!/usr/bin/env python 
from cyclopts import App, Parameter
from typing import Literal,Annotated
import os
import json

build_benchmark_data=App()

@build_benchmark_data.default
def default_action(
    set: Literal["minos","variantiq-synthetic","generate-synthetic"] = "minos",
    pipeline_inputs_only: bool = False,
    comparison_vcf_only: bool = False,
    script_template: str = None,
    datasets_definitions: str = "/benchmark_dataset_definitions",
    output_directory: str = "./benchmark_data"
):
    """
    Parameters
    ----------
    set: string
        The Benchmarking Dataset you would like to download.\n
        minos - A set of reads (from SRA), reference genomes (from NCBI), and truth genomes (from minos)\n 
        variantiq-synthetic - A set of synthetic reads, reference genomes, and truth genomes pre-generated by the VariantIQ team\n 
        generate-synthetic - This will generate a new set of synthetic reads, reference genomes, and truth genomes.  Which can be used locally.\n 
        Note: If you generate new synthetic data and want to compare against the standardized VariantIQ pipelines, those pipelines will need to be run locally.
    
    pipeline_inputs_only: bool
        When building the benchmark datasets, only download the reads, reference genomes, and truth genomes.  Do not download the comparison VCFs
        pre-run with the standardized VariantIQ pipelines.  Does not apply to the "generate-synthetic" set.

    comparison_vcf_only: bool
        Only download the set of VCF files built from the VariantIQ standardized pipelines.  Does not apply to the "generate-synthetic" set

    script_template: str
        Path to template to generate script for each sample [Not Implemented]

    datasets_definitions: str
        Path to folder containing dataset download definitions.  Should not be changed unless you know something.
    
    output_directory: str
        Path to output folder. The folder will be created if it doesn't exist.  If it does exist, as the builder runs, it will check to see if file exist already
        before re-downloading them 
    """
    print(f"Building Benchmark Data: {set}")

    try:
        os.mkdir( output_directory, 0o755 );
        print (f"Created Folder: {output_directory}")
    except FileExistsError as err:
        print(f"Output folder already exists, continuing.")
    except OSError as err:
        print(f"Error creating output folder: {err}")
        exit(1)

    try:
        with open(f'{datasets_definitions}/metadata.json') as f:
            dataset_definition = json.load(f)
    except Exception as err:
        print(f"Error reading dataset definition metadata.json:\n\n{err}")        

    print(f"Samples File: {dataset_definition.samples}")

build_benchmark_data()