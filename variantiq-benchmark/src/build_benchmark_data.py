#!/usr/bin/env python 
from cyclopts import App
from typing import Literal,Union
import os
import os.path
import json
import subprocess
import csv
import requests
import shutil
import tarfile

vcf_download_url="https://nssac.bii.virginia.edu/~dm8qs/variantiq_data"
synthetic_data_download_url="https://nssac.bii.virginia.edu/~cm4su/variantiq_data"
FASTQDUMP=["scif","run","fastq-dump"]

build_benchmark_data=App()

@build_benchmark_data.default
def default_action(
    dataset: Literal["minos","minos-single","variantiq-synthetic","generate-synthetic"] = "minos",
    platform: Literal["pacbio"] = "pacbio",
    pipeline_inputs_only: bool = False,
    comparison_vcf_only: bool = False,
    script_template: str = None,
    datasets_definitions: str = "/benchmark_dataset_definitions",
    output_directory: str = "/output"
):
    """
    Parameters
    ----------
    dataset: str
        The Benchmarking Dataset you would like to download.\n
        minos - A set of reads (from SRA), reference genomes (from NCBI), and truth genomes (from minos)\n 
        variantiq-synthetic - A set of synthetic reads, reference genomes, and truth genomes pre-generated by the VariantIQ team\n 
        generate-synthetic - This will generate a new set of synthetic reads, reference genomes, and truth genomes.  Which can be used locally.\n 
        Note: If you generate new synthetic data and want to compare against the standardized VariantIQ pipelines, those pipelines will need to be run locally.
    
    platform: str
        The platform used to create the read files.  Currently only supports Illumina/PacBio reads.

    pipeline_inputs_only: bool
        When building the benchmark datasets, only download the reads, reference genomes, and truth genomes.  Do not download the comparison VCFs
        pre-run with the standardized VariantIQ pipelines.  Does not apply to the "generate-synthetic" set.

    comparison_vcf_only: bool
        Only download the set of VCF files built from the VariantIQ standardized pipelines.  Does not apply to the "generate-synthetic" set

    script_template: str
        Path to template to generate script for each sample [Not Implemented]

    datasets_definitions: str
        Path to folder containing dataset download definitions.  Should not be changed unless you know something.
    
    output_directory: str
        Path to output folder. The folder will be created if it doesn't exist.  If it does exist, as the builder runs, it will check to see if file exist already
        before re-downloading them 
    """
    print(f"Building Benchmark Data: {dataset}")
    
    # ----------------------------------------------------------------------
    # SPECIAL CASE: variantiq_synthetic
    # ----------------------------------------------------------------------
    if dataset == "variantiq-synthetic":
        print("Special dataset detected: variantiq-synthetic")

        archive_name = "variantiq-synthetic.bz2"
        download_url = f"{synthetic_data_download_url}/{archive_name}"
        target_file = os.path.join(output_directory, archive_name)

        # Download only if not already expanded
        if not os.path.exists(target_file) and not os.path.exists(f"{target_file}.expanded"):
            print(f"Downloading: {download_url}")
            download_url_to_file(download_url, target_file, True)

            print("Extracting dataset...")
            with tarfile.open(target_file, "r:bz2") as tar:
                tar.extractall(path=output_directory)

            # Mark as expanded
            with open(f"{target_file}.expanded", "w") as fp:
                pass

            print(f"Removing {target_file}")
            os.remove(target_file)

        print(f"Dataset ready in: {output_directory}")
        return

    try:
        os.mkdir( output_directory, 0o755 )
        print (f"Created Folder: {output_directory}")
    except FileExistsError as err:
        print(f"Output folder already exists, continuing.")
    except OSError as err:
        print(f"Error creating output folder: {err}")
        exit(1)

    data_def=None
    try:
        with open(f'{datasets_definitions}/{dataset}/metadata.json') as f:
            data_def = json.load(f)
    except FileNotFoundError:
        print(f"No metadata.json provided for dataset definition.  Assume defaults.")
        data_def = {
            "samples": "samples.csv"
        }
        print(f"Default Dataset Definition: {json.dumps(data_def)}")
    except Exception as err:
        print(f"Error reading dataset definition metadata.json:\n\n{err}")    
        exit(1)    


    sample_file = data_def.get("samples","samples.csv")
    prerun_script = data_def.get("prerun_script", None)

    if not comparison_vcf_only:
        if prerun_script is not None:
            call_prerun_script(prerun_script,output_directory,f"{datasets_definitions}/{dataset}",datasets_definitions)
                
        f = f"{datasets_definitions}/{dataset}/{sample_file}"
        process_samples(f"{datasets_definitions}/{dataset}/{sample_file}",f"{datasets_definitions}/{dataset}",pipeline_inputs_only,comparison_vcf_only,output_directory,data_def,dataset)

    if not pipeline_inputs_only:
        get_comparison_vcfs(dataset,data_def,output_directory)


def call_prerun_script(script_file,output_directory,dataset_definition_folder,datasets_definitions):
    print("Pre-run data retrieval step")
    result = subprocess.run([f"{dataset_definition_folder}/{script_file}",output_directory], capture_output=True, text=True)
    print(f"Results: \n{result.stdout}\n{result.stderr}")

def getReadsFromSRA(sraid,target_folder,data_def,dataset):
    """
    Checks if a truth genome has already been downloaded in the target folder, and if not
    retrieves it.

    Args:
        sraid (str): SRA Accession
        target_folder (str): The file path to save the read files
        data_def (dict): The dataset definition
    """
    try:
        if dataset == "minos-single":
            cmd = FASTQDUMP + ["-O", target_folder, sraid]
            subprocess.run(cmd, check=True, capture_output=True, text=True)

            single_read_file = f"{target_folder}/{sraid}.fastq"
            if os.path.exists(single_read_file):
                os.rename(single_read_file, f"{target_folder}/read_1.fastq")
                return [f"{target_folder}/read_1.fastq"]
            else:
                raise FileNotFoundError(f"Expected single read file not found: {single_read_file}")

        else:
            cmd = FASTQDUMP + ["--split-files", "-O", target_folder, sraid]
            subprocess.run(cmd, check=True, capture_output=True, text=True)

            read1 = f"{target_folder}/{sraid}_1.fastq"
            read2 = f"{target_folder}/{sraid}_2.fastq"

            if os.path.exists(read1) and os.path.exists(read2):
                os.rename(read1, f"{target_folder}/read_1.fastq")
                os.rename(read2, f"{target_folder}/read_2.fastq")
                return [f"{target_folder}/read_1.fastq", f"{target_folder}/read_2.fastq"]
            else:
                raise FileNotFoundError("Expected paired read files not found.")
                
    except Exception as err:
        print(f"Error running fastq-dump: {err}")
        exit(1)

def getReadFiles(read_files:Union[str,list],target_folder,row, data_def_folder,data_def,output_root,dataset):
    """
    Checks if a read_files has already been downloaded in the target folder, and if not
    retrieves it.

    Args:
        read_files (Union[str,list]): Reference to the read_files.  
        target_folder (str): The file path to save the read_files
        row (dict): The entire row of data about the sample
        data_def_folder (str): The path to the folder containing the dataset definition
        data_def (dict): The dataset definition
        output_root (str): The root output folder for the data build
    """
    if not os.path.exists(f"{target_folder}/read_1.fastq") or not os.path.exists(f"{target_folder}/read_2.fastq"):
        print(f"Get Read Files: {read_files}")
        if data_def.get("get_read_files_script",False):
            raise NotImplemented("Run Script to get data_def")
        elif isinstance(read_files,str):
            if read_files.startswith("http[s]://"):
                raise NotImplemented(f"Downloading readfiles from {read_files}")
            elif read_files.startswith("/"):
                raise NotImplemented(f"Copying files from local directory")
            else:
                return getReadsFromSRA(read_files,target_folder,data_def,dataset)

def getReferenceGenome(reference_genome,target_folder,row,data_def_folder,data_def,output_root):
    """
    Checks if a reference genome has already been downloaded in the target folder, and if not
    retrieves it.

    Args:
        reference_genome (str): Reference to the reference genome.  
        target_folder (str): The file path to save the reference genome
        row (dict): The entire row of data about the sample
        data_def_folder (str): The path to the folder containing the dataset definition
        data_def (dict): The dataset definition
        output_root (str): The root output folder for the data build
    """
    target_file = f"{target_folder}/reference_genome.fasta"
    if not os.path.exists(target_file): 
        print(f"Get Reference Genome: {reference_genome}")
        print(f"Data Def Folder: {data_def_folder}")
        if data_def.get("get_reference_genome_script",False):
            cmd=[f"{data_def_folder}/{data_def.get('get_reference_genome_script')}",output_root,reference_genome,target_folder]
            result = subprocess.run(cmd, capture_output=True, text=True)
            print(f"Results: \n{result.stdout}\n{result.stderr}")

        else:
            if reference_genome.startswith("http://") or reference_genome.startswith("https://"):
                download_url_to_file(reference_genome,target_file)
            elif reference_genome.startswith("/"):
                raise NotImplemented(f"Copying files from local directory")
            else:
                #treat as ncbi accession
                url =f"https://www.ncbi.nlm.nih.gov/sviewer/viewer.fcgi?id={reference_genome}&db=nuccore&report=fasta&extrafeat=null&conwithfeat=on&hide-cdd=on"
                download_url_to_file(url,target_file)

    return target_file

def getTruthGenome(truth_genome,target_folder,row,data_def_folder,data_def,output_root):
    """
    Checks if a truth genome has already been downloaded in the target folder, and if not
    retrieves it.

    Args:
        truth_genome (str): Reference to the truth genome.  
        target_folder (str): The file path to save the truth genome
        row (dict): The entire row of data about the sample
        data_def_folder (str): The path to the folder containing the dataset definition
        data_def (dict): The dataset definition
        output_root (str): The root output folder for the data build
    """
    target_file = f"{target_folder}/truth_genome.fasta"
    if not os.path.exists(target_file): 
        print(f"Get Truth Genome: {truth_genome}")
        if data_def.get("get_truth_genome_script",False):
            cmd=[f"{data_def_folder}/{data_def.get('get_truth_genome_script')}",output_root,truth_genome,target_folder]
            result = subprocess.run(cmd, capture_output=True, text=True)
            # print(f"result: {result.stdout} {result.stderr}")
        else:
            if truth_genome.startswith("http://") or truth_genome.startswith("https://"):
                download_url_to_file(truth_genome,target_file)
            elif truth_genome.startswith("/"):
                raise NotImplemented(f"Copying files from local directory")
            else:
                raise Exception(f"Uknown Truth Genome Reference: {truth_genome}")
    else:
        print("Found truth genome")
    return target_file

def download_url_to_file(url: str, target_file: str, silent:bool) -> None:
    """
    Downloads the contents of the given URL and saves it to the specified file.

    Args:
        url (str): The HTTP or HTTPS URL to download.
        target_file (str): The file path to save the downloaded content.

    Raises:
        ValueError: If the URL is not HTTP or HTTPS.
        requests.RequestException: If there's an error during the HTTP request.
        IOError: If there's an error writing to the file.
    """
    try:
        # Send an HTTP GET request
        response = requests.get(url, stream=True)
        response.raise_for_status()  # Raise an error for HTTP response codes 4xx/5xx

        # Write the content to the target file
        with open(target_file, 'wb') as file:
            for chunk in response.iter_content(chunk_size=8192):
                file.write(chunk)

        if not silent:
            print(f"Content downloaded successfully and saved to '{target_file}'")

    except requests.RequestException as e:
        print(f"HTTP request error: {e}")
        raise
    except IOError as e:
        print(f"File write error: {e}")
        raise

def get_comparison_vcfs(dataset,data_def,output_directory):
    try:
        url = f"{vcf_download_url}/variantiq-data.json"
        # Send an HTTP GET request
        response = requests.get(url, {"accept": "application/json"})
        response.raise_for_status()  # Raise an error for HTTP response codes 4xx/5xx
        vcf_config = response.json()
        for key in vcf_config[dataset]:
            print(f"Downloading: {vcf_config[dataset][key]}")
            target_file = f"{output_directory}/{vcf_config[dataset][key]}"
            if not os.path.exists(target_file) and not os.path.exists(f"{target_file}.expanded"):
                download_url_to_file(f"{vcf_download_url}/{vcf_config[dataset][key]}",target_file,True)
                print(f"Extracting VCFs.")
                with tarfile.open(target_file,"r") as tar:
                    tar.extractall(path=output_directory)
                    with open(f"{target_file}.expanded","w") as fp:
                        pass
                    print(f"Removing {target_file}.")
                    os.remove(target_file)
            
    except Exception as err:
        print(f"Error retrieving vcf config file from {url}")
        exit(1)

def populate_sample_folder(name,read_files,reference_genome,truth_genome,row, pipeline_inputs_only,comparison_vcf_only,output_directory,data_def_folder,data_def,dataset):
    """
    Create the sample folder in the output directory

    Args:
        name (str): Sample file name,
        read_files(Union[str,list]): Read Files reference for sample
        reference_genome (str): Reference Genome for sample
        truth_genome (str): Truth Genome for sample
        row (dict): Entire sample row
        pipeline_inputs_only (bool): Only retrieve the pipeline inputs
        comparison_vcf_only (bool): Only retrieve benchmark vcfs
        output_directory (str): Location to build the data
        data_def_folder (str): Path to the dataset definition folder
        data_def(dict): Dataset definition
    """
    try:
        sample_folder = f"{output_directory}/{name}"
        os.mkdir(sample_folder)
    except FileExistsError:
        pass
    except Exception as err:
        print(f"Error creating sample folder: {sample_folder}: {err}")
        exit(1)

    try:
        metadata = {"name": name}
        if not comparison_vcf_only:
            metadata['read_files'] = getReadFiles(read_files,sample_folder,row,data_def_folder,data_def,output_directory,dataset)
            print(f"Downloaded Read Files: {metadata['read_files']}")
            metadata['reference_genome'] = getReferenceGenome(reference_genome,sample_folder,row,data_def_folder,data_def,output_directory)
            print(f"Downloaded Reference Genome: {metadata['reference_genome']}")
            metadata['truth_genome'] = getTruthGenome(truth_genome,sample_folder,row,data_def_folder,data_def,output_directory)

        # with open(f"{sample_folder}/metadata.json", 'w') as f:
        #     json.dump(metadata, f)
        
    except Exception as err:
        print(f"Error populating sample folder: {err}")
        exit(1)

def process_samples(sample_file,data_def_folder,pipeline_inputs_only,comparison_vcf_only,output_directory,data_def,dataset):
    shutil.copyfile(sample_file,f"{output_directory}/benchmark_samples.csv")
    with open(sample_file, 'r') as f:       
        print(f"Reading Sample CSV: {sample_file}")
        csv_reader = csv.DictReader(f, delimiter=',')
        for row in csv_reader:
            populate_sample_folder(row["sample_name"],row['read_files'],row['reference_genome'],row['truth_genome'],row,pipeline_inputs_only,comparison_vcf_only,output_directory,data_def_folder,data_def,dataset)


